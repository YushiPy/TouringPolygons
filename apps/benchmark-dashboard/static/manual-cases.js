export function createManualCaseController(deps) {
	const {
		$,
		askConfirmation,
		autoGeneratedSticker,
		campaignExists,
		casePayload,
		cloneCaseData,
		closeCampaignModal,
		deleteCampaign,
		emptyCaseData,
		escapeHTML,
		instanceLabel,
		manualEditor,
		refresh,
		requestJSON,
		setCloseIcon,
		setTrashIcon,
		sortCampaigns,
		sortInstances,
		state,
		switchPanel,
	} = deps;

	function editableCampaigns() {
		return state.campaigns;
	}

	function renderManualCampaigns() {
		const grid = $("#manual-campaign-grid");
		if (!grid) {
			return;
		}
		grid.innerHTML = "";
		const campaigns = sortCampaigns(editableCampaigns(), state.manualCampaignSort);
		if (!campaigns.some((campaign) => campaign.name === state.manualCampaign)) {
			state.manualCampaign = campaigns[0]?.name || "";
		}
		if (campaigns.length === 0) {
			grid.innerHTML = '<div class="empty-choice">No campaigns yet.</div>';
			grid.appendChild(newManualCampaignButton());
			renderManualCases();
			return;
		}
		for (const campaign of campaigns) {
			const row = document.createElement("div");
			row.className = "manual-campaign-row";
			row.dataset.value = campaign.name;
			const button = document.createElement("div");
			button.className = "choice-card manual-campaign-select";
			button.setAttribute("role", "option");
			button.tabIndex = 0;
			button.innerHTML = `
				<strong>
					<span class="drag-handle" title="Drag to reorder" aria-label="Drag to reorder" role="img">⠿</span>
					<span data-campaign-name-slot></span>
					${campaign.type === "manual" ? "" : autoGeneratedSticker()}
				</strong>
				<span>${campaign.instance_progress.total || 0} instances</span>
			`;
			button.querySelector("[data-campaign-name-slot]").appendChild(manualCampaignNameControl(campaign));
			const actions = document.createElement("div");
			actions.className = "manual-campaign-actions";
			const deleteButton = document.createElement("button");
			deleteButton.type = "button";
			deleteButton.className = "danger campaign-edit-delete";
			deleteButton.dataset.deleteCampaign = campaign.name;
			deleteButton.setAttribute("aria-label", `Delete ${campaign.name}`);
			setTrashIcon(deleteButton);
			deleteButton.addEventListener("click", (event) => {
				event.stopPropagation();
				deleteCampaign(event);
			});
			actions.appendChild(deleteButton);
			row.append(button, actions);
			button.addEventListener("click", (event) => {
				if (!event.target.closest(".campaign-name-button, .campaign-name-input, .drag-handle")) {
					selectManualCampaign(campaign.name);
				}
			});
			button.addEventListener("keydown", (event) => {
				if (event.key === "Enter" || event.key === " ") {
					event.preventDefault();
					selectManualCampaign(campaign.name);
				}
			});
			const handle = button.querySelector(".drag-handle");
			handle.addEventListener("mousedown", (event) => event.preventDefault());
			handle.draggable = state.manualCampaignSort === "default";
			handle.addEventListener("dragstart", (event) => {
				if (state.manualCampaignSort !== "default") {
					event.preventDefault();
					return;
				}
				row.classList.add("is-dragging");
				event.dataTransfer.effectAllowed = "move";
				setDragPreview(event, row, campaign.name);
				event.dataTransfer.setData("text/plain", campaign.name);
			});
			handle.addEventListener("dragend", () => {
				row.classList.remove("is-dragging");
				clearDropMarkers(grid);
			});
			row.addEventListener("dragover", (event) => {
				event.preventDefault();
				markDropTarget(row, event);
			});
			row.addEventListener("dragleave", (event) => {
				if (!row.contains(event.relatedTarget)) clearDropMarker(row);
			});
			row.addEventListener("drop", async (event) => {
				event.preventDefault();
				const source = event.dataTransfer.getData("text/plain");
				const position = dropPosition(row, event);
				clearDropMarkers(grid);
				if (!source || source === campaign.name || state.manualCampaignSort !== "default") return;
				await reorderCampaigns(source, campaign.name, position);
			});
			grid.appendChild(row);
		}
		grid.appendChild(newManualCampaignButton());
		grid.querySelectorAll(".manual-campaign-row").forEach((row) => {
			row.classList.toggle("is-active", row.dataset.value === state.manualCampaign);
			row.querySelector(".choice-card")?.classList.toggle("is-active", row.dataset.value === state.manualCampaign);
		});
	}

	function renderManualCases() {
		const root = $("#manual-case-list");
		if (!root) {
			return;
		}
		root.innerHTML = "";
		if (!state.manualCampaign) {
			root.textContent = "Create or select a manual campaign.";
			state.manualCases = [];
			manualEditor.draw();
			return;
		}
		if (state.manualCases.length === 0) {
			root.innerHTML = '<div class="empty-choice">No instances yet.</div>';
			root.appendChild(newManualCaseButton());
			manualEditor.draw();
			return;
		}
		for (const { item, index } of sortInstances(state.manualCases, state.manualInstanceSort)) {
			root.appendChild(manualCaseRow(item, index));
		}
		root.appendChild(newManualCaseButton());
		manualEditor.draw();
	}

	function newManualCaseButton() {
		const button = document.createElement("button");
		button.type = "button";
		button.className = "new-manual-case-row secondary";
		button.textContent = "+";
		button.title = "New instance";
		button.setAttribute("aria-label", "New instance");
		button.addEventListener("click", newManualCase);
		return button;
	}

	function newManualCampaignButton() {
		const button = document.createElement("button");
		button.type = "button";
		button.className = "new-manual-campaign-row secondary";
		button.textContent = "+";
		button.title = "New campaign";
		button.setAttribute("aria-label", "New campaign");
		button.addEventListener("click", createNewManualCampaign);
		return button;
	}

	function manualCaseRow(item, index) {
		const active = index === state.manualCaseIndex;
		const row = document.createElement("div");
		row.className = "manual-case-row";
		row.classList.toggle("is-active", active);
		row.dataset.caseIndex = String(index);
		row.append(manualCaseSelect(item, index, active), manualCaseActions(index));
		const handle = row.querySelector(".drag-handle");
		handle.addEventListener("mousedown", (event) => event.preventDefault());
		handle.draggable = state.manualInstanceSort === "default";
		handle.addEventListener("dragstart", (event) => {
			if (state.manualInstanceSort !== "default") {
				event.preventDefault();
				return;
			}
			row.classList.add("is-dragging");
			event.dataTransfer.effectAllowed = "move";
			setDragPreview(event, row, item.name || `Instance ${instanceLabel(index)}`);
			event.dataTransfer.setData("text/plain", String(index));
		});
		handle.addEventListener("dragend", () => {
			row.classList.remove("is-dragging");
			clearDropMarkers(row.parentElement);
		});
		row.addEventListener("dragover", (event) => {
			event.preventDefault();
			markDropTarget(row, event);
		});
		row.addEventListener("dragleave", (event) => {
			if (!row.contains(event.relatedTarget)) clearDropMarker(row);
		});
		row.addEventListener("drop", (event) => {
			event.preventDefault();
			const sourceIndex = Number(event.dataTransfer.getData("text/plain"));
			const position = dropPosition(row, event);
			clearDropMarkers(row.parentElement);
			if (Number.isInteger(sourceIndex) && sourceIndex !== index && state.manualInstanceSort === "default") {
				reorderManualCases(sourceIndex, index, position);
			}
		});
		return row;
	}

	function manualCaseSelect(item, index, active) {
		const selectArea = document.createElement("div");
		selectArea.className = "manual-case-select";
		selectArea.setAttribute("role", active ? "group" : "button");
		if (!active) {
			selectArea.tabIndex = 0;
		}
		const count = document.createElement("span");
		count.dataset.casePolygonCount = "";
		count.innerHTML = polygonCountLabel(item);
		const handle = document.createElement("span");
		handle.className = "drag-handle";
		handle.textContent = "⠿";
		handle.title = "Drag to reorder";
		handle.setAttribute("aria-label", "Drag to reorder");
		handle.setAttribute("role", "img");
		handle.draggable = state.manualInstanceSort === "default";
		selectArea.append(handle, manualCaseNameControl(item, index), count);
		const select = () => selectManualCase(index, active);
		selectArea.addEventListener("click", select);
		selectArea.addEventListener("keydown", (event) => {
			if (event.key === "Enter" || event.key === " ") {
				event.preventDefault();
				select();
			}
		});
		return selectArea;
	}

	function manualCampaignNameControl(campaign) {
		if (state.manualCampaignRenaming === campaign.name) {
			const input = document.createElement("input");
			input.className = "campaign-name-input";
			input.value = campaign.name;
			const commit = () => finishRenameManualCampaign(campaign.name, input.value);
			input.addEventListener("click", (event) => event.stopPropagation());
			input.addEventListener("blur", commit);
			input.addEventListener("keydown", (event) => {
				event.stopPropagation();
				if (event.key === "Enter") {
					event.preventDefault();
					commit();
				} else if (event.key === "Escape") {
					event.preventDefault();
					state.manualCampaignRenaming = null;
					renderManualCampaigns();
				}
			});
			requestAnimationFrame(() => {
				input.focus();
				input.select();
			});
			return input;
		}
		const button = document.createElement("button");
		button.type = "button";
		button.className = "campaign-name-button";
		button.textContent = campaign.name;
		button.addEventListener("click", (event) => {
			event.stopPropagation();
			state.manualCampaignRenaming = campaign.name;
			renderManualCampaigns();
		});
		return button;
	}

	function manualCaseNameControl(item, index) {
		if (state.manualRenamingIndex === index) {
			const input = document.createElement("input");
			input.className = "instance-name-input";
			input.value = item.name || `Instance ${instanceLabel(index)}`;
			const commit = () => finishRenameManualCase(index, input.value);
			input.addEventListener("click", (event) => event.stopPropagation());
			input.addEventListener("blur", commit);
			input.addEventListener("keydown", (event) => {
				event.stopPropagation();
				if (event.key === "Enter") {
					event.preventDefault();
					commit();
				} else if (event.key === "Escape") {
					event.preventDefault();
					state.manualRenamingIndex = null;
					renderManualCases();
				}
			});
			requestAnimationFrame(() => {
				input.focus();
				input.select();
			});
			return input;
		}
		const button = document.createElement("button");
		button.type = "button";
		button.className = "instance-name-button";
		button.textContent = item.name || `Instance ${instanceLabel(index)}`;
		button.addEventListener("click", (event) => {
			event.stopPropagation();
			renameManualCase(index);
		});
		return button;
	}

	function manualCaseActions(index) {
		const actions = document.createElement("div");
		actions.className = "manual-case-actions";
		const duplicateButton = document.createElement("button");
		duplicateButton.type = "button";
		duplicateButton.className = "secondary manual-case-action";
		duplicateButton.textContent = "⧉";
		duplicateButton.title = "Duplicate";
		duplicateButton.setAttribute("aria-label", `Duplicate instance ${instanceLabel(index)}`);
		duplicateButton.addEventListener("click", () => duplicateManualCase(index));
		const deleteButton = document.createElement("button");
		deleteButton.type = "button";
		deleteButton.className = "danger manual-case-action";
		setCloseIcon(deleteButton);
		setTrashIcon(deleteButton);
		deleteButton.title = "Delete";
		deleteButton.setAttribute("aria-label", `Delete instance ${instanceLabel(index)}`);
		deleteButton.addEventListener("click", (event) => deleteManualCase(index, { skipConfirm: event.shiftKey }));
		actions.append(duplicateButton, deleteButton);
		return actions;
	}

	function polygonCountLabel(item) {
		return `${item.polygons.length} polygons${item.generated ? autoGeneratedSticker("This instance was generated automatically.") : ""}`;
	}

	function dropPosition(element, event) {
		const rect = element.getBoundingClientRect();
		return event.clientY >= rect.top + rect.height / 2 ? "after" : "before";
	}

	function clearDropMarker(element) {
		element?.classList.remove("is-drop-before", "is-drop-after");
	}

	function clearDropMarkers(root) {
		root?.querySelectorAll(".is-drop-before, .is-drop-after").forEach(clearDropMarker);
	}

	function markDropTarget(element, event) {
		clearDropMarkers(element.parentElement);
		element.classList.add(dropPosition(element, event) === "after" ? "is-drop-after" : "is-drop-before");
	}

	function setDragPreview(event, row, label) {
		const ghost = row.cloneNode(true);
		ghost.classList.add("drag-preview");
		ghost.querySelectorAll("button, input").forEach((element) => element.remove());
		ghost.style.width = `${row.getBoundingClientRect().width}px`;
		const name = ghost.querySelector(".campaign-name-button, .instance-name-button");
		if (name) name.textContent = label;
		document.body.appendChild(ghost);
		event.dataTransfer.setDragImage(ghost, 18, 18);
		requestAnimationFrame(() => ghost.remove());
	}

	function reorderManualCases(sourceIndex, targetIndex, position = "before") {
		const activeCase = state.manualCases[state.manualCaseIndex];
		const [caseData] = state.manualCases.splice(sourceIndex, 1);
		let insertIndex = position === "after" ? targetIndex + 1 : targetIndex;
		if (sourceIndex < insertIndex) insertIndex -= 1;
		state.manualCases.splice(insertIndex, 0, caseData);
		state.manualCaseIndex = state.manualCases.indexOf(activeCase);
		renderManualCases();
		manualEditor.changed();
		scheduleManualAutosave({ immediate: true });
	}

	async function reorderCampaigns(sourceName, targetName, position = "before") {
		const names = sortCampaigns(state.campaigns, "default").map((campaign) => campaign.name);
		const sourceIndex = names.indexOf(sourceName);
		const targetIndex = names.indexOf(targetName);
		if (sourceIndex < 0 || targetIndex < 0) return;
		const [name] = names.splice(sourceIndex, 1);
		let insertIndex = names.indexOf(targetName);
		if (position === "after") insertIndex += 1;
		names.splice(insertIndex, 0, name);
		try {
			const data = await requestJSON("/api/campaigns/order", { method: "PUT", body: JSON.stringify({ names }) });
			const byName = new Map(data.campaigns.map((campaign) => [campaign.name, campaign]));
			state.campaigns = names.map((name) => byName.get(name)).filter(Boolean);
			renderManualCampaigns();
			deps.onCampaignOrderUpdated?.();
		} catch (error) {
			manualEditor.setSaveStatus(error.message);
		}
	}

	function selectManualCase(index, active) {
		if (active) {
			return;
		}
		state.manualCaseIndex = index;
		manualEditor.activePolygon = null;
		manualEditor.solutionPath = null;
		renderManualCases();
		manualEditor.frameCurrentCase();
		manualEditor.scheduleSolve();
	}

	function updateManualCaseListMetadata() {
		const current = manualEditor.currentCase();
		const row = document.querySelector(`.manual-case-row[data-case-index="${state.manualCaseIndex}"]`);
		const label = row?.querySelector("[data-case-polygon-count]");
		if (label && current) {
			label.innerHTML = polygonCountLabel(current);
		}
	}

	function renameManualCase(index) {
		const current = state.manualCases[index];
		if (!current) {
			return;
		}
		state.manualRenamingIndex = index;
		renderManualCases();
	}

	function finishRenameManualCase(index, value) {
		const current = state.manualCases[index];
		if (!current) {
			return;
		}
		state.manualRenamingIndex = null;
		current.name = value.trim();
		renderManualCases();
		scheduleManualAutosave({ immediate: true });
	}

	function uniqueCampaignName() {
		const names = new Set(state.campaigns.map((campaign) => campaign.name));
		let index = 1;
		while (names.has(`Campaign ${index}`)) index += 1;
		return `Campaign ${index}`;
	}

	async function createNewManualCampaign() {
		const name = uniqueCampaignName();
		try {
			const data = await requestJSON("/api/campaigns/manual", {
				method: "POST",
				body: JSON.stringify({ name, overwrite: false }),
			});
			await refresh();
			await selectManualCampaign(data.campaign.name);
			state.manualCampaignRenaming = data.campaign.name;
			renderManualCampaigns();
		} catch (error) {
			manualEditor.setStatus(error.message);
		}
	}

	async function finishRenameManualCampaign(oldName, value) {
		const nextName = value.trim();
		state.manualCampaignRenaming = null;
		if (!nextName || nextName === oldName) {
			renderManualCampaigns();
			return;
		}
		if (campaignExists(nextName)) {
			manualEditor.setSaveStatus(`Campaign "${nextName}" already exists.`);
			renderManualCampaigns();
			return;
		}
		try {
			const data = await requestJSON(`/api/campaigns/${encodeURIComponent(oldName)}/rename`, {
				method: "PUT",
				body: JSON.stringify({ name: nextName }),
			});
			const index = state.campaigns.findIndex((campaign) => campaign.name === oldName);
			if (index !== -1) state.campaigns[index] = data.campaign;
			if (state.manualCampaign === oldName) state.manualCampaign = nextName;
			if (state.loadedManualCampaign === oldName) state.loadedManualCampaign = nextName;
			if (state.selectedCampaign === oldName) state.selectedCampaign = nextName;
			if (state.selectedComparisonCampaign === oldName) state.selectedComparisonCampaign = nextName;
			if (state.campaignCaseMetadata.has(oldName)) {
				state.campaignCaseMetadata.set(nextName, state.campaignCaseMetadata.get(oldName));
				state.campaignCaseMetadata.delete(oldName);
			}
			renderManualCampaigns();
			deps.onCampaignOrderUpdated?.();
		} catch (error) {
			manualEditor.setSaveStatus(error.message);
			renderManualCampaigns();
		}
	}

	async function selectManualCampaign(name) {
		state.manualCampaign = name;
		state.loadedManualCampaign = "";
		state.manualCases = [];
		state.manualCaseIndex = 0;
		renderManualCampaigns();
		await loadManualCases(name);
	}

	async function loadManualCases(name) {
		if (!name) {
			renderManualCases();
			return;
		}
		try {
			const data = await requestJSON(`/api/campaigns/${encodeURIComponent(name)}/cases`);
			state.manualCases = data.cases.map(cloneCaseData);
			state.campaignCaseMetadata.set(name, state.manualCases.map(cloneCaseData));
			state.loadedManualCampaign = name;
			state.manualCaseIndex = Math.min(state.manualCaseIndex, Math.max(0, state.manualCases.length - 1));
			clearTimeout(state.manualAutosaveTimer);
			renderManualCases();
			manualEditor.frameCurrentCase();
			manualEditor.scheduleSolve();
		} catch (error) {
			manualEditor.setStatus(error.message);
		}
	}

	async function loadCampaignCaseMetadata(campaignName) {
		if (state.campaignCaseMetadata.has(campaignName)) {
			return state.campaignCaseMetadata.get(campaignName);
		}
		try {
			const data = await requestJSON(`/api/campaigns/${encodeURIComponent(campaignName)}/cases`);
			const cases = data.cases.map(cloneCaseData);
			state.campaignCaseMetadata.set(campaignName, cases);
			return cases;
		} catch {
			state.campaignCaseMetadata.set(campaignName, []);
			return [];
		}
	}

	async function editInstance(campaign, index) {
		closeCampaignModal();
		await selectManualCampaign(campaign.name);
		state.manualCaseIndex = Math.min(index, Math.max(0, state.manualCases.length - 1));
		renderManualCases();
		switchPanel("cases-panel");
		manualEditor.frameCurrentCase();
		manualEditor.scheduleSolve();
	}

	async function saveManualCasesNow() {
		if (!state.manualCampaign) {
			manualEditor.setSaveStatus("Select a campaign first.");
			return;
		}
		if (state.manualAutosaving) {
			state.manualAutosaveQueued = true;
			return;
		}
		const campaignName = state.manualCampaign;
		state.manualAutosaving = true;
		manualEditor.setSaveStatus("Saving...");
		try {
			const data = await requestJSON(`/api/campaigns/${encodeURIComponent(campaignName)}/cases?refresh_previews=false`, {
				method: "PUT",
				body: JSON.stringify({ cases: state.manualCases.map(casePayload) }),
			});
			if (state.manualCampaign === campaignName) {
				const campaignIndex = state.campaigns.findIndex((campaign) => campaign.name === data.campaign.name);
				if (campaignIndex === -1) {
					state.campaigns.push(data.campaign);
				} else {
					state.campaigns[campaignIndex] = data.campaign;
				}
				state.loadedManualCampaign = campaignName;
				state.campaignCaseMetadata.set(campaignName, state.manualCases.map(cloneCaseData));
				renderManualCampaigns();
				deps.onCampaignUpdated?.(data.campaign);
				manualEditor.setSaveStatus("Autosaved.");
			}
		} catch (error) {
			manualEditor.setSaveStatus(error.message);
		} finally {
			state.manualAutosaving = false;
			if (state.manualAutosaveQueued) {
				state.manualAutosaveQueued = false;
				scheduleManualAutosave({ immediate: true });
			}
		}
	}

	function scheduleManualAutosave(options = {}) {
		if (!state.manualCampaign) {
			return;
		}
		clearTimeout(state.manualAutosaveTimer);
		if (options.immediate) {
			saveManualCasesNow();
			return;
		}
		state.manualAutosaveTimer = setTimeout(saveManualCasesNow, 1200);
	}

	function newManualCase() {
		if (!state.manualCampaign) {
			manualEditor.setSaveStatus("Create or select a campaign first.");
			return;
		}
		state.manualCases.push(emptyCaseData());
		state.manualCaseIndex = state.manualCases.length - 1;
		manualEditor.activePolygon = null;
		manualEditor.solutionPath = null;
		renderManualCases();
		manualEditor.frameCurrentCase();
		manualEditor.changed();
		scheduleManualAutosave({ immediate: true });
	}

	function duplicateManualCase(index = state.manualCaseIndex) {
		const current = state.manualCases[index] || manualEditor.currentCase();
		if (!current) {
			newManualCase();
			return;
		}
		state.manualCases.splice(index + 1, 0, cloneCaseData(current));
		state.manualCaseIndex = index + 1;
		renderManualCases();
		manualEditor.frameCurrentCase();
		manualEditor.changed();
		scheduleManualAutosave({ immediate: true });
	}

	async function deleteManualCase(index = state.manualCaseIndex, options = {}) {
		if (!state.manualCampaign || state.manualCases.length === 0) {
			return;
		}
		if (!options.skipConfirm && !(await askConfirmation(`Delete instance ${instanceLabel(index)} from "${state.manualCampaign}"?`, "Delete"))) {
			return;
		}
		state.manualCases.splice(index, 1);
		state.manualCaseIndex = Math.min(state.manualCaseIndex, Math.max(0, state.manualCases.length - 1));
		manualEditor.activePolygon = null;
		manualEditor.solutionPath = null;
		renderManualCases();
		manualEditor.changed();
		scheduleManualAutosave({ immediate: true });
	}

	return {
		deleteManualCase,
		duplicateManualCase,
		editInstance,
		loadCampaignCaseMetadata,
		loadManualCases,
		newManualCase,
		renderManualCampaigns,
		renderManualCases,
		scheduleManualAutosave,
		selectManualCampaign,
		updateManualCaseListMetadata,
		reorderCampaigns,
	};
}
