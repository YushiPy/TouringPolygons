test("case data helpers clone and normalize cases", () => {
	const original = { name: "demo", generated: true, start: [0, 1], target: [2, 3], polygons: [[[0, 0], [1, 0]], [[0, 0], [1, 0], [0, 1]]] };
	const clone = cloneCaseData(original);
	clone.polygons[1][0][0] = 9;
	assert.equal(original.polygons[1][0][0], 0);
	assert.deepEqual(casePayload(original).polygons, [[[0, 0], [1, 0], [0, 1]]]);
	assert.deepEqual(emptyCaseData(), { name: "", generated: false, start: [0, 0], target: [1, 0], polygons: [] });
	assert.equal(instanceLabel(3), 4);
});

test("command builders preserve selected options", () => {
	const values = { name: "demo", threads: "4", solver: "binary", max_calls: "500", max_instances: "2", max_seconds: "3" };
	const form = {
		querySelector: (selector) => ({ checked: selector.includes("force") || selector.includes("no_build") }),
		querySelectorAll: () => [{ value: "binary" }, { value: "tan" }],
	};
	const originalFormData = globalThis.FormData;
	globalThis.FormData = class {
		entries() { return Object.entries(values); }
	};
	try {
		assert.match(runCommandFromForm(form), /--solver binary_search_lazy/);
		assert.match(runCommandFromForm(form), /--threads 4/);
		assert.match(compareCommandFromForm(form), /--solver binary_search_lazy/);
	} finally {
		globalThis.FormData = originalFormData;
	}
});

test("report utilities parse common timing and solver values", () => {
	assert.equal(parseDurationSeconds("250ms"), 0.25);
	assert.deepEqual(parseTimingDetail("1.5s (25%)"), { value: 1.5, time: "1.5s", percent: "25%" });
	assert.equal(meanSecondsPerCall({ convex_solver_seconds: "2", total_convex_calls: "4" }), 0.5);
	assert.equal(instanceTotalSeconds({ decomposition_seconds: "1", approximation_seconds: "2", bnb_seconds: "3" }), 6);
	assert.equal(shortNumber(1200), "1200.0");
	assert.equal(solverLabel("binary"), "Binary Intersections");
	assert.deepEqual(findTable({ tables: [{ title: "Summary" }] }, "Summary"), { title: "Summary" });
});

test("job utilities classify job state consistently", () => {
	const job = { kind: "comparison", status: "running", solver_progress_total: 2, solver_progress_completed: 1, progress_total: 10, progress_completed: 4 };
	assert.equal(jobPanel(job), "comparison-panel");
	assert.equal(jobKindLabel(job), "Comparison");
	assert.equal(jobProgressLabel(job), "1/2 solvers, 4/10 instances");
	assert.equal(jobTerminalState({ status: "completed" }), "completed");
	assert.equal(jobDockStatusClass({ status: "failed" }), "is-failed");
});
